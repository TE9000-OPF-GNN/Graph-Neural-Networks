"""Task 088: exec-based tests of the Contingency notebook's loading helpers.

Contingency code cells are exec'd in order in a fresh namespace (IPython magics commented out, toggles cell skipped).
Real-data tests are skipped if their input is missing. The tiny N-1 dataset is generated by exec'ing the DataGen cells
(as in task 087's test) into a pytest tmp dir; the source index is only read.
"""
# [STSI 141026]:new loading-helper tests for the contingency notebook (task 088)
import json
import os
import sys

import pytest

REPO = os.path.dirname(os.path.abspath(__file__))
CONTINGENCY = os.path.join(REPO, "GNN_Powerflow_V2.7_Contingency.ipynb")
DATAGEN = os.path.join(REPO, "GNN_Powerflow_V2.6_DataGen.ipynb")
TOGGLES_MARKER = "run_contingency_eval = False"
S8_NAME = "sweep_S8_new_curriculum.json"

# first DataGen code cell containing each marker is exec'd, in this order (same list as test_n1_datagen_generation.py)
_DATAGEN_MARKERS = [
    "import pypsa",
    "TRAINING_NETWORKS_DIR =",
    "def solve_power_flow_with_slack(",
    "def add_ieee9_branches(",
    "def save_dataset_list(",
    "N-1 CONTINGENCY: LIMITS (task 086)",
    "# ==== N-1 CONTINGENCY: GENERATION (task 087) ====",
    "# ==== N-1 CONTINGENCY: DRIVER (task 087) ====",
]


def _clean(src):
    out = []
    for line in src.split("\n"):
        st = line.lstrip()
        out.append(line[: len(line) - len(st)] + "#" + st if st.startswith(("%", "!")) else line)
    return "\n".join(out)


def _code_sources(path):
    with open(path, encoding="utf-8") as fh:
        cells = json.load(fh)["cells"]
    return [("".join(c["source"]) if isinstance(c["source"], list) else c["source"])
            for c in cells if c["cell_type"] == "code"]


def _exec_contingency():
    ns = {"__name__": "__task088_test__"}
    for i, src in enumerate(_code_sources(CONTINGENCY)):
        if TOGGLES_MARKER in src:
            continue
        exec(compile(_clean(src), f"<contingency:code{i}>", "exec"), ns)  # noqa: S102
    return ns


@pytest.fixture(scope="module")
def ns():
    namespace = _exec_contingency()
    main = sys.modules["__main__"]
    had, old = hasattr(main, "PowerFlowGNN"), getattr(main, "PowerFlowGNN", None)
    main.PowerFlowGNN = namespace["PowerFlowGNN"]  # unpickling resolves the class from __main__
    yield namespace
    if had:
        main.PowerFlowGNN = old
    else:
        del main.PowerFlowGNN


def test_exec_all_code_cells_fresh_namespace():
    ns_ = _exec_contingency()
    for name in ("load_runs_by_key", "load_n1_dataset", "load_source_base_nets", "PowerFlowGNN",
                 "PowerFlowDataset", "evaluate_gnn_on_test_set", "build_ref_baselines", "reconstruct_test_split",
                 "global_mean_pool", "spearmanr", "precision_recall_fscore_support", "deque", "runpf"):
        assert name in ns_, name
    assert "run_contingency_eval" not in ns_ and "run_ref_timing" not in ns_   # toggles cell skipped
    srcs = _code_sources(CONTINGENCY)
    tog = [s for s in srcs if TOGGLES_MARKER in s]
    assert len(tog) == 1 and "run_ref_timing = False" in tog[0]


# ── trained runs (D6) ────────────────────────────────────────────────────────
def _s8_path(ns_):
    p = os.path.join(ns_["TRAINING_RESULTS_DIR"], S8_NAME)
    if not os.path.isfile(p):
        pytest.skip(f"sweep file not found: {p}")
    return p


def test_load_runs_by_key_s8(ns):
    import torch
    p = _s8_path(ns)
    key = ns["load_sweep_results"](p)[0]["run_key"]
    got = ns["load_runs_by_key"]([key], [p])
    assert list(got) == [key]
    model = got[key]["model"]
    assert isinstance(model, torch.nn.Module)
    assert model.angle_mode == "edge_delta"
    assert got[key]["_source_pkl"] == p


def test_load_runs_by_key_missing_key_raises(ns):
    p = _s8_path(ns)
    missing = "__no_such_run_key_088__"
    with pytest.raises(KeyError) as exc:
        ns["load_runs_by_key"]([missing], [p])
    assert missing in str(exc.value)


def test_load_runs_by_key_empty_raises(ns):
    with pytest.raises(ValueError):
        ns["load_runs_by_key"]([], [])


# ── N-1 dataset (D9) ─────────────────────────────────────────────────────────
@pytest.fixture(scope="module")
def n1(tmp_path_factory):
    dg = {"__name__": "__task088_datagen__"}
    srcs = _code_sources(DATAGEN)
    for marker in _DATAGEN_MARKERS:
        src = next((s for s in srcs if marker in s), None)
        assert src is not None, marker
        exec(compile(src, f"<datagen:{marker}>", "exec"), dg)  # noqa: S102
    if not os.path.isdir(dg["DATA_ROOT"]):
        pytest.skip(f"DATA_ROOT not found: {dg['DATA_ROOT']}")
    source = os.path.join(dg["TRAINING_NETWORKS_DIR"], "mixed_1500_w.json")
    if not os.path.isfile(source):
        pytest.skip(f"dataset not found: {source}")
    out_dir = tmp_path_factory.mktemp("n1_088")
    summary = dg["generate_n1_contingency_dataset"](source, 1, "pytest088", out_dir=str(out_dir))
    return dict(summary=summary, source=source)


def test_load_n1_dataset(ns, n1):
    nets, header, rows = ns["load_n1_dataset"](n1["summary"]["index_path"])
    solved = rows[rows.status == "solved"]
    assert len(solved) > 0
    assert len(nets) == len(solved)
    assert "rows" not in header and header["tag"] == "n1_mixed_1500_w_pytest088"
    for i, net in enumerate(nets):
        outage = rows.loc[rows.file_position == i, "outage_name"]
        assert len(outage) == 1
        assert outage.iloc[0] not in net.lines.index


def test_load_source_base_nets(ns, n1):
    nets, _, rows = ns["load_n1_dataset"](n1["summary"]["index_path"])
    bases = ns["load_source_base_nets"](rows)
    assert len(bases) == 1
    (src, pos), base = next(iter(bases.items()))
    assert os.path.normcase(os.path.abspath(src)) == os.path.normcase(os.path.abspath(n1["source"]))
    assert pos == int(rows.source_position.iloc[0])
    for net in nets:
        assert list(net.buses.index) == list(base.buses.index)
