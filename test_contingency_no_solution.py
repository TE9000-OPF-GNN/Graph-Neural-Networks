def _solved(n1):
    return n1["rows"][n1["rows"].status == "solved"]


def _base(n1, row):
    return n1["bases"][(row["source_index"], int(row["source_position"]))]


def _rebuild(ns, n1, row):
    return ns["rebuild_post_outage_net"](_base(n1, row), row, n1["real"], n1["synth"])


def _assert_state_equal(a, b, what):
    assert set(a) == set(b), what
    for f in a:
        pd.testing.assert_frame_equal(a[f], b[f], check_exact=False, atol=ATOL, rtol=0,
                                      obj=f"{what}[{f}]")


# ── limits / rebuild ─────────────────────────────────────────────────────────
def test_decode_line_limits(ns, n1):
    dg, rows = n1["dg"], n1["rows"]
    systems = set(rows.system)
    assert set(n1["real"]) == systems
    for s in systems:
        assert n1["real"][s] == dg["load_real_line_ratings"](s), s
    pairs = []
    for (src, pos), base in n1["bases"].items():
        sys_ = rows.loc[(rows.source_index == src) & (rows.source_position == pos), "system"].unique()
        assert len(sys_) == 1
        pairs.append((sys_[0], base))
    expected = dg["compute_synthetic_line_limits"](pairs, n1["header"]["alpha"])
    assert set(n1["synth"]) == set(expected)
    k = sorted(expected)
    np.testing.assert_array_equal([n1["synth"][x] for x in k], [expected[x] for x in k])   # NaN-equal


def test_rebuild_matches_solved_nc(ns, n1):
    solved = _solved(n1)
    assert len(solved) > 0
    before = {k: (list(b.lines.index), b.buses_t.v_mag_pu.copy(), b.buses_t.p.copy()) for k, b in n1["bases"].items()}
    for _, row in solved.iterrows():
        nc = n1["nets"][int(row["file_position"])]
        net = _rebuild(ns, n1, row)
        assert list(net.lines.index) == list(nc.lines.index), row["case_id"]
        np.testing.assert_array_equal(net.lines["s_limit_pu"].to_numpy(dtype=float),
                                      nc.lines["s_limit_pu"].to_numpy(dtype=float))
        assert list(net.lines["limit_source"]) == list(nc.lines["limit_source"]), row["case_id"]
    for k, b in n1["bases"].items():
        lines, vm, p = before[k]
        assert list(b.lines.index) == lines
        pd.testing.assert_frame_equal(b.buses_t.v_mag_pu, vm)
        pd.testing.assert_frame_equal(b.buses_t.p, p)
    row = solved.iloc[0]
    assert row["outage_name"] in _base(n1, row).lines.index


