# ── input parity (premise check, D10b(i)) ────────────────────────────────────
def test_input_parity_graph(ns, n1):
    # same constructor args as predict_network_results_with_masks for a node-mode, 7-feature model
    kw = dict(use_edge_features=True, use_pnom_share=False, angle_mode="node", ptdf_branch_mode="lines")
    for _, row in _solved(n1).iterrows():
        nc = n1["nets"][int(row["file_position"])]
        ds_r = ns["PowerFlowDataset"]([_rebuild(ns, n1, row)], **kw)
        ds_n = ns["PowerFlowDataset"]([nc], **kw)
        assert len(ds_r) == len(ds_n) == len(nc.snapshots)
        for t in range(len(ds_n)):
            a, b = ds_r[t], ds_n[t]
            tag = f"case {row['case_id']} ({row['system']}, {row['outage_name']}) snapshot {t}"
            assert torch.equal(a.edge_index, b.edge_index), f"edge_index differs: {tag}"
            assert torch.allclose(a.edge_attr, b.edge_attr, atol=ATOL), f"edge_attr differs: {tag}"
            assert torch.allclose(a.x, b.x, atol=ATOL), \
                f"x differs: {tag}; max |dx| per column {(a.x - b.x).abs().max(dim=0).values.tolist()}"


