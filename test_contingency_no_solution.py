            m = g.merge(r, on=on, how="outer", suffixes=("_g", "_r"), indicator=True)
            assert (m["_merge"] == "both").all(), (p, key)
            for c in labels:
                assert (m[f"{c}_g"].astype(bool) == m[f"{c}_r"].astype(bool)).all(), (p, key, c)


